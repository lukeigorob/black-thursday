// Merges the per-group research files (historical_data/black_thursday/groups/*.json) into the database
// files and writes the research progress report. Run again whenever a group's file changes:
//   node scripts/history/merge.mjs
// Writes aircraft.json, crew.json, squadrons.json, mission_outcomes.json, research_gaps.json and
// RESEARCH_PROGRESS.md beside the group files' folder. Nothing is added or guessed here: it only gathers
// what the group files say (a sortie filed under two groups, marked duplicate_of, is counted once).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FORCE, TOTALS } from '../../src/oob.js';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../../historical_data/black_thursday');
const groups = readdirSync(join(dir, 'groups')).filter((f) => f.endsWith('.json') && !f.endsWith('_sources.json'))
  .map((f) => JSON.parse(readFileSync(join(dir, 'groups', f), 'utf8')));
const oob = JSON.parse(readFileSync(join(dir, 'bomb_groups.json'), 'utf8'));
const planned = new Map(); // group -> aircraft the game flies for it (oob.js)
for (const w of FORCE) for (const g of w.groups) { planned.set(g.group, (planned.get(g.group) ?? 0) + g.n); if (g.attach) planned.set(g.attach.group, (planned.get(g.attach.group) ?? 0) + g.attach.n); }

const aircraft = [], crew = [], squadrons = new Map(), outcomes = [], gaps = [];
for (const g of groups) {
  for (const a of g.aircraft ?? []) {
    if (a.duplicate_of) continue;
    const id = a.serial_number ?? `${g.group}:${a.pilot ?? 'unknown'}:${aircraft.length}`;
    const { crew: men = [], ...rest } = a;
    aircraft.push({ id, bomb_group: g.group, ...rest, crew_count: men.length });
    for (const m of men) crew.push({ aircraft: id, bomb_group: g.group, mission_date: '1943-10-14', ...m });
    if (a.bomb_squadron) {
      const k = `${g.group}/${a.bomb_squadron}`, s = squadrons.get(k) ?? { bomb_group: g.group, bomb_squadron: a.bomb_squadron, codes: new Set(), aircraft: 0 };
      if (a.squadron_code) s.codes.add(a.squadron_code); s.aircraft++; squadrons.set(k, s);
    }
    outcomes.push({ aircraft: id, bomb_group: g.group, serial_number: a.serial_number ?? null, nickname: a.nickname ?? null, pilot: a.pilot ?? null, mission_outcome: a.mission_outcome ?? 'unknown', loss_details: a.loss_details ?? null, macr: a.macr ?? null, confidence: a.historical_confidence ?? 'UNKNOWN', sources: a.sources ?? [] });
  }
  for (const r of g.research_gaps ?? []) gaps.push({ bomb_group: g.group, gap: r });
}
const save = (f, d) => writeFileSync(join(dir, f), `${JSON.stringify(d, null, 1)}\n`);
// the surnames the crew can call (src/crewnames.js: the voice lines are recorded for each, lines.js)
const surnameOf = (n) => { const w = String(n).replace(/,/g, '').split(/\s+/).filter(Boolean); while (w.length > 1 && /^(jr\.?|sr\.?|ii|iii|iv)$/i.test(w[w.length - 1])) w.pop(); return w[w.length - 1]; };
const named = (m) => m.name && m.confidence !== 'UNKNOWN';
const allSur = [...new Set(crew.filter(named).map((m) => surnameOf(m.name)))].sort();
const pilotSur = [...new Set(crew.filter((m) => named(m) && m.position === 'pilot').map((m) => surnameOf(m.name)))].sort();
writeFileSync(join(dir, '../../src/crewnames.js'), `// Generated by scripts/history/merge.mjs from historical_data/black_thursday: the surnames of the real crewmen
// of 14 October 1943 the intercom can call (lines.js records a clip for each). Don't edit by hand.
export const CREW_SURNAMES = ${JSON.stringify(allSur)};
export const PILOT_SURNAMES = ${JSON.stringify(pilotSur)};
`);
save('aircraft.json', aircraft);
save('crew.json', crew);
save('squadrons.json', [...squadrons.values()].map((s) => ({ ...s, codes: [...s.codes] })));
save('mission_outcomes.json', outcomes);
save('research_gaps.json', gaps);

// ---- the progress report
const C = (x) => x === 'VERIFIED' || x === 'PROBABLE';
const ROLES = ['pilot', 'copilot', 'navigator', 'bombardier', 'engineer', 'radio', 'ball', 'tail'];
const full = (a) => ROLES.every((r) => (a.crew ?? []).some((m) => m.position === r)) && (a.crew ?? []).filter((m) => /waist/.test(m.position)).length >= 2;
const rows = [...planned.keys()].map((name) => {
  const g = groups.find((x) => x.group === name), list = (g?.aircraft ?? []).filter((a) => !a.duplicate_of && !a.did_not_fly);
  const o = oob.find((x) => x.group === name);
  return {
    name, flown: planned.get(name), identified: list.length, serials: list.filter((a) => a.serial_number && C(a.historical_confidence)).length,
    names: list.filter((a) => a.nickname).length, manifests: list.filter(full).length, men: list.reduce((n, a) => n + (a.crew?.length ?? 0), 0),
    lost: list.filter((a) => a.mission_outcome === 'lost').length, lostOob: o?.lost ?? null,
  };
});
const sum = (k) => rows.reduce((n, r) => n + r[k], 0);
const lines = [
  '# Black Thursday research progress', '',
  `Generated by \`scripts/history/merge.mjs\` from \`historical_data/black_thursday/groups/\`. Mission 115, Schweinfurt, 14 October 1943: ${TOTALS.all} B-17s dispatched (1st Air Division ${TOTALS['1st']}, 3rd ${TOTALS['3rd']}), 60 lost.`, '',
  '**The database is not complete.** Every gap below is a real gap in what could be found and checked, not filled in. In the game, an unidentified bomber has no serial or name, and its crew are placeholders, marked as such.', '',
  '| | Count |', '|---|---|',
  `| Aircraft identified | ${sum('identified')} of ${TOTALS.all} |`,
  `| With a serial (VERIFIED or PROBABLE) | ${sum('serials')} |`,
  `| With a recorded name (nickname) | ${sum('names')} (most PROBABLE: names for this date are rarely confirmed) |`,
  `| Complete crew manifests (all ten stations) | ${sum('manifests')} |`,
  `| Crewmen named | ${sum('men')} |`,
  `| Losses identified (aircraft recorded lost) | ${sum('lost')} of 60 |`,
  `| Markings painted from the records | ${aircraft.filter((a) => a.serial_number).length} tail numbers, ${aircraft.filter((a) => a.squadron_code).length} squadron codes, ${aircraft.filter((a) => a.nickname).length} names (group symbols for all 16 groups; nose art not drawn: not documented) |`, '',
  '| Group | Flown in the game | Identified | Serials | Names | Full crews | Men named | Lost (records) | Lost (order of battle) |', '|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.flown} | ${r.identified} | ${r.serials} | ${r.names} | ${r.manifests} | ${r.men} | ${r.lost} | ${r.lostOob ?? '?'} |`), '',
  '## Records still to research', '',
  ...rows.filter((r) => r.identified < r.flown).map((r) => `- **${r.name}:** ${r.flown - r.identified} of ${r.flown} aircraft not identified.`), '',
  '## Gaps noted by the research, by group', '',
  ...gaps.map((x) => `- ${x.bomb_group}: ${x.gap}`), '',
];
writeFileSync(join(dir, 'RESEARCH_PROGRESS.md'), lines.join('\n'));
console.log(`${aircraft.length} aircraft, ${crew.length} crewmen, ${outcomes.filter((o) => o.mission_outcome === 'lost').length} recorded lost; report written`);
